#!/usr/bin/env bash
# 门禁：**两个参考目录的登记表不许与实际分叉**（`docs/plans/README.md` · `docs/reviews/README.md`）。
#
# 断言（真正的强制力在 `tools/doc-registry.py` 的 `ASSERTIONS` 与 `--check` 的逐字节比对）：
#   · **人口下限**：`docs/plans` ≥ 10 份 · `docs/reviews` ≥ 60 份 —— ⛔ 目录搬了 / 命名变了
#     ⇒ **响亮失败**，不许「登记表只剩几行」也照样绿（这就是「扫不到就报绿」那一族）；
#   · **文档不陈旧**：重新生成 ⇒ **逐字节相同**（陈旧 ⇒ 红，并指出首个不同的行）；
#   · **解析面自证**：表里每一行都必须是 `.md`（⛔ 不是名字对不上还照样列）。
#
# 为什么要有它（用户 2026-10-02 逐字）：
#   「之前的 `plan/` 确实是**各种讨论记录**……**只适合当记录**……**适合当参考**，
#    **施工时不适合拿来看**」
# ⭐ 两个目录的共同病是**看不出来里面是什么** ⇒ 这份登记表把「**每份自称是什么**」摆上台面。
#
# ⚠️ 它**不是**效力门禁：表里写着「报告」不等于它能当依据 —— 效力仍是
#    「**可引、⛔ 不可当依据**」（那条由 `survey/README.md` 与本表**都说**，⛔ 不靠门禁）。
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 tools/doc-registry.py --check
