#!/usr/bin/env bash
# 门禁：**施工计划书不许与现实分叉**（`docs/DOC_REFACTOR_PLAN.md` ↔ 仓库现状）。
#
# 断言（真正的强制力在 `tools/plan-doc-refactor.py` 的 `LIVE` 表与 `--check`）：
#   · **活读数逐条复算**：每条读数都带「怎么重算」⇒ 与实测不符 ⇒ 红
#     （⭐ 这是本门禁存在的**唯一理由**：草案 §C 那份 6 步顺序在 9 处被施工推翻，
#      而**没有任何东西会因此报错** —— 因为没有执行载体）；
#   · **人口下限**：活读数 ≥ 5 条 · 工序 ≥ 5 波 / 25 条 —— 清单被删空 ⇒ **响亮失败**；
#   · **计划书不陈旧**：重新生成 ⇒ **逐字节相同**（陈旧 ⇒ 红，并指出首个不同的行）。
#
# 为什么要有它（用户 2026-10-02 逐字）：
#   「**先修订草案，再以此修订完整施工计划书**，现在还没有施工计划书载体**就先创一个**」
#   「**当实际施工情况比设计草案时变化太多，应该是停下来修订草案，而不是强行推进**」
# ⭐ 「停下来修订」需要一个能**发现"该停了"**的机关 ⇒ 本门禁就是那个机关（`C-2`）。
#
# ⚠️ 它**不是**排期门禁、也不是验收门禁：它只保证**计划书与现实的读数一致**。
#    进度（哪条做完没做完）是**人写的状态列**，⛔ 本门禁不猜它。
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 tools/plan-doc-refactor.py --check
