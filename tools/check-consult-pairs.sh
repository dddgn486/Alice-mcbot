# 门禁：**咨询通道必须成对**（用户 2026-10-04 裁 **ⓐ：未配对的问题文档 ⇒ `check-all` 直接红**）。
#
# 用户令（逐字，见 `consult/README.md` 与 `docs/QUESTIONS_LEDGER.md` `Q-033`）：
#   · 「通道的载体就是**在仓库新加一个目录**，一个子目录放**现状问题文档**，一个子目录放**回执**，
#      **带编号**，**两边必须成对出现**，才能算完成一次咨询」
#   · 「只要**提交出咨询请求**，就**必须等咨询完成才能继续工作**」
#
# ⇒ ⭐ 本门禁的红 = **这一轮不许往下走**，⛔ 不是"这份文件写错了"。
# 真正的强制力在 `tools/check-consult-pairs.py`：
#   · 未配对的问题 ⇒ 红（核心）· 孤儿回执 ⇒ 红 · 编号重复 ⇒ 红 · 同号不同名 ⇒ 红
#   · 人口下限（问题侧不许为空）⇒ 红 · 两个子目录任缺一个 ⇒ **响亮失败**
#   · 8 条注入自证臂（`--selftest`；⭐ 由 `check-selftests` 汇总跑）
#
# ⚠️ ⛔ 它**不判**「有没有人偷偷把问题解决了」—— ⭐ 机械判不了（如实写在脚本头）。
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 tools/check-consult-pairs.py
