#!/usr/bin/env bash
# 门禁：**Python 字符串里不许嵌裸 ASCII 双引号**（`tools/*.py`）。
#
# ⭐ 为什么有它（出处 = 2026-10-02 的真实损失，⛔ 不是洁癖）：
#   主工作流在**同一个文件**（`tools/plan-doc-refactor.py`）上**连续 4 次**犯同一个错 ——
#   在 `A("…")` 的正文里用 ASCII `"` 包中文词 ⇒ 字符串提前闭合 ⇒ `SyntaxError`。
#   ⚠️ 恶毒之处：**写的时候"看着像对的"**，⛔ 只在 `py_compile` 那一刻暴露；
#   而本项目的"那一刻"=`check-all` ⇒ **要跑整套门禁才知道自己写坏了**。
#   ⭐ 这正是 `docs/HANDOVER.md` §G 那族（**静默错写进地基**）⇒ 变成本门禁（纪律：门禁 > 散文）。
#
# 断言（真正的强制力在 `tools/check-quote-lint.py`）：
#   · **语法臂**：每个被扫的 `.py` 必须 `ast.parse` 通过（⭐ 4 次真错 100% 命中这道）；
#   · **可疑臂**：`A('…"…')` 这种语法侥幸通过、语义上几乎肯定是同一个错 ⇒ 红；
#   · **人口下限**：`.py` ≥ 20 —— 范围/解析崩塌 ⇒ **响亮失败**（扫不到就报绿是不放过的）；
#   · **豁免不静默**：`# quote-lint: example` 逐行生效，且**被计数打印**。
#
# ⚠️ 诚实边界：它**只管引号形状**，⛔ 不查语义；⛔ 不扫 `.sh`／`.md`（引号规则不同）。
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 tools/check-quote-lint.py
