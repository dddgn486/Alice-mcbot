# 门禁：`docs/upper-design/`（**架构级／跨包设计**那一层）—— 2026-10-06 立；
#   出处 = 开发者当日逐字：「不要创建 `docs/CROSS_PACKAGE_DESIGN.md`，而是创建一个 **`docs/upper-design`** 目录，
#   这个目录用来放**架构级或者跨包的设计**，但是这里面的**每个文档创建必须我审核**，
#   而且**一定要纳入当前体系管理**，**修改也要我审批**」。
#
# ⭐ 为什么有它：那两句是**规则**，而本仓的纪律是「**门禁 > 散文**」——
#   ⛔ 散文会过期、会被绕过、语义会分歧；⭐ **能让构建失败的东西才算边界**。
#
# 判据（**四条**，强制力在 `tools/check-upper-docs.py`，**九臂**注入自证）：
#   · **① 新件必须登记**（`D − B ≠ ∅` ⇒ 红）= 「**创建必须我审核**」；
#   · **② 不许留假账**（`B − D ≠ ∅` ⇒ 红）—— 登记了却不在磁盘上；⭐ 删也要他批；
#   · **③ 改一个字节也要重批**（`sha256` 不符 ⇒ 红）= 「**修改也要我审批**」；
#   · **④ 必须带 `**类标**` 且类号 = `⑧`**（`§D′-1` ⑧ 设计）= 「**纳入当前体系管理**」。
#
# ⭐ **`--write` = 开发者的批准动作**（⛔ **不是**"重新生成一下"）⇒ 它会**逐条打印批准了什么** ＋ 写后自查。
# ⚠️ **它判不了什么**：⛔ 判不了「这份设计**对不对**」—— 那是人审核本身，不是门禁的活。
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 tools/check-upper-docs.py
