#!/usr/bin/env bash
# 门禁：**注入臂必须真的跑** —— 汇总跑全部 `--selftest`（用户 2026-10-04 裁「②丁」）。
#
# ⭐ 为什么有它（当场量到的形状）：`tools/` 下的门禁大多带"注入自证臂"，
#   但 ⛔ `check-all` 只跑 `--check` ⇒ ⭐ **臂从来没被跑过**。AST 全量分类：
#     · A 类 **8** 个：每次运行都跑臂（inline）—— ✅ 没问题；
#     · ⭐ B 类 **18** 个：**只有 `--selftest` 才跑臂** ⇒ ⛔ 在 `check-all` 里**从没跑过**；
#     · C 类 41 个：没有臂。
#
# ⭐ 两个活样本（这条为什么值钱）：
#   ① `tools/cleanup-classify.py` 的臂 F 曾因**自污染恒红** —— ⛔ **没有任何东西会因此变红**
#      （2026-10-04 断点七十二 才发现并修好）；
#   ② `tools/check-expected-reds.py` 的文件头**逐字写着**「`--selftest` 的 8 条合成臂**每次都跑**」，
#      ⛔ 而代码里**只有 `--selftest` 才跑** ⇒ ⭐ **散文与代码相反**。
#
# 为什么是"另开一道汇总门禁"（用户选「②丁」）而不是逐条挂进 `check-all`：
#   ⭐ 那样要动 **18 道已有门禁**的语义；汇总门禁 ⛔ 不动它们，而且**臂红了它自己报是哪一条**。
#
# 判据（强制力在 `tools/check-selftests.py`，**5 臂**注入自证）：
#   · 名单里每条**必须真的带 `--selftest`**（⛔ 写错名 / 标志被删 ⇒ 红：解析不到就响亮失败）；
#   · 每条**必须真的过**（判 **退出码**；⛔ **不看它自己打印的 `PASS`** —— 那正是本门禁要防的自报成功）；
#   · **人口下限** `FLOOR`（名单被删空 ⇒ 红）＋ **环境档只许变短**（`ENV_SKIP_MAX`）。
#
# ⚠️ 环境档（⛔ 不静默）：`recipe-graph` 缺原版数据目录 ⇒ 它**不是通过，是没执行**，
#   ⭐ 会**逐条打印成 WARN**，⛔ 且名单不许再长 —— 与 `check-all` 现有两条环境 WARN 同口径。
set -euo pipefail
cd "$(dirname "$0")/.."
exec python3 tools/check-selftests.py --check
